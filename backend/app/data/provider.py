"""Generic maritime provider contract used by domain-facing services."""

from collections.abc import Mapping
from typing import Any, Protocol


class MaritimeDataProvider(Protocol):
    name: str

    async def get_vessel_location(self, identifier: str) -> Mapping[str, Any]: ...

    async def get_vessel_details(self, identifier: str) -> Mapping[str, Any]: ...

    async def get_vessel_history(self, identifier: str, date_range: str) -> Mapping[str, Any]: ...

    async def get_vessels_by_area(self, area: Mapping[str, float]) -> Mapping[str, Any]: ...

    async def get_port_calls(self, identifier: str, *, by_port: bool = False) -> Mapping[str, Any]: ...

    async def get_route(self, origin: str, destination: str) -> Mapping[str, Any]: ...

    async def health(self) -> Mapping[str, Any]: ...
